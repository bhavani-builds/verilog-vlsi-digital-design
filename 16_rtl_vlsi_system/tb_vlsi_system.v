`timescale 1ns/1ps

// ============================================================
// INTEGRATED RTL VLSI SYSTEM TESTBENCH
// ============================================================

module tb_vlsi_system;

    reg clk;
    reg reset;

    reg [3:0] A;
    reg [3:0] B;

    reg [2:0] OP;

    reg load;

    reg enable;
    reg up_down;

    wire [3:0] alu_result;
    wire alu_carry;
    wire alu_zero;

    wire [3:0] registered_result;

    wire [3:0] counter_value;


    // ========================================================
    // DUT
    // ========================================================

    vlsi_system DUT (

        .clk(clk),
        .reset(reset),

        .A(A),
        .B(B),

        .OP(OP),

        .load(load),

        .enable(enable),
        .up_down(up_down),

        .alu_result(alu_result),
        .alu_carry(alu_carry),
        .alu_zero(alu_zero),

        .registered_result(registered_result),

        .counter_value(counter_value)

    );


    // ========================================================
    // CLOCK
    // ========================================================

    initial begin

        clk = 1'b0;

        forever #5 clk = ~clk;

    end


    // ========================================================
    // TEST
    // ========================================================

    initial begin

        $display("================================================");
        $display("       INTEGRATED RTL VLSI SYSTEM");
        $display("================================================");

        $display(
            "TIME | A    B    OP | ALU  C Z | REG  | COUNT"
        );

        $monitor(
            "%0t | %b   %b   %b  | %b   %b %b | %b   | %b",
            $time,
            A,
            B,
            OP,
            alu_result,
            alu_carry,
            alu_zero,
            registered_result,
            counter_value
        );


        // ====================================================
        // RESET
        // ====================================================

        reset = 1'b1;

        A = 4'b0000;
        B = 4'b0000;

        OP = 3'b000;

        load = 1'b0;

        enable = 1'b0;

        up_down = 1'b1;

        #20;

        reset = 1'b0;


        // ====================================================
        // ADD
        // A = 5
        // B = 3
        // Result = 8
        // ====================================================

        A = 4'b0101;
        B = 4'b0011;

        OP = 3'b000;

        load = 1'b1;

        #10;


        // ====================================================
        // AND
        // ====================================================

        load = 1'b0;

        OP = 3'b010;

        #10;


        // ====================================================
        // OR
        // ====================================================

        OP = 3'b011;

        #10;


        // ====================================================
        // XOR
        // ====================================================

        OP = 3'b100;

        #10;


        // ====================================================
        // ADD WITH CARRY
        // 15 + 1 = 16
        // 4-bit result = 0000
        // Carry = 1
        // ====================================================

        A = 4'b1111;
        B = 4'b0001;

        OP = 3'b000;

        load = 1'b1;

        #10;


        // ====================================================
        // COUNTER UP
        // ====================================================

        load = 1'b0;

        enable = 1'b1;

        up_down = 1'b1;

        repeat (5)

            @(posedge clk);


        // ====================================================
        // COUNTER DOWN
        // ====================================================

        up_down = 1'b0;

        repeat (3)

            @(posedge clk);


        // ====================================================
        // FINISH
        // ====================================================

        #10;

        $display("================================================");
        $display("       TESTBENCH COMPLETED");
        $display("================================================");

        $finish;

    end

endmodule
