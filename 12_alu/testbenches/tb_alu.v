// ============================================================
// TESTBENCH: 4-BIT ALU
// ============================================================

`timescale 1ns/1ps

module tb_alu;

    reg [3:0] A;
    reg [3:0] B;

    reg [2:0] OP;

    wire [3:0] RESULT;
    wire CARRY;
    wire ZERO;


    // ========================================================
    // DUT
    // ========================================================

    alu_4bit DUT (
        .A(A),
        .B(B),
        .OP(OP),
        .RESULT(RESULT),
        .CARRY(CARRY),
        .ZERO(ZERO)
    );


    // ========================================================
    // TASK FOR DISPLAY
    // ========================================================

    task run_test;

        input [2:0] operation;

        begin

            OP = operation;

            #10;

            $display(
                "A=%b B=%b OP=%b | RESULT=%b CARRY=%b ZERO=%b",
                A,
                B,
                OP,
                RESULT,
                CARRY,
                ZERO
            );

        end

    endtask


    // ========================================================
    // TEST
    // ========================================================

    initial begin

        $display("");
        $display("================================================");
        $display("               4-BIT ALU TEST");
        $display("================================================");

        A = 4'b0101;
        B = 4'b0011;


        // ----------------------------------------------------
        // ADD
        // 5 + 3 = 8
        // ----------------------------------------------------

        run_test(3'b000);


        // ----------------------------------------------------
        // SUBTRACT
        // 5 - 3 = 2
        // ----------------------------------------------------

        run_test(3'b001);


        // ----------------------------------------------------
        // AND
        // 0101 & 0011 = 0001
        // ----------------------------------------------------

        run_test(3'b010);


        // ----------------------------------------------------
        // OR
        // 0101 | 0011 = 0111
        // ----------------------------------------------------

        run_test(3'b011);


        // ----------------------------------------------------
        // XOR
        // 0101 ^ 0011 = 0110
        // ----------------------------------------------------

        run_test(3'b100);


        // ----------------------------------------------------
        // NOT A
        // ~0101 = 1010
        // ----------------------------------------------------

        run_test(3'b101);


        // ----------------------------------------------------
        // SHIFT LEFT
        // 0101 << 1 = 1010
        // ----------------------------------------------------

        run_test(3'b110);


        // ----------------------------------------------------
        // SHIFT RIGHT
        // 0101 >> 1 = 0010
        // ----------------------------------------------------

        run_test(3'b111);


        // ----------------------------------------------------
        // ADDITION WITH CARRY
        // 1111 + 0001 = 1_0000
        // ----------------------------------------------------

        A = 4'b1111;
        B = 4'b0001;

        run_test(3'b000);


        // ----------------------------------------------------
        // ZERO FLAG
        // 0101 - 0101 = 0000
        // ----------------------------------------------------

        A = 4'b0101;
        B = 4'b0101;

        run_test(3'b001);


        $display("");
        $display("================================================");
        $display("             ALU TEST COMPLETED");
        $display("================================================");

        $finish;

    end

endmodule
