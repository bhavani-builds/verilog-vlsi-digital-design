// ============================================================
// TESTBENCH: 4-BIT REGISTER
// ============================================================

`timescale 1ns/1ps

module tb_registers;

    reg clk;
    reg reset;
    reg load;

    reg [3:0] D;

    wire [3:0] Q;


    // ========================================================
    // DUT
    // ========================================================

    register_4bit DUT (
        .clk(clk),
        .reset(reset),
        .load(load),
        .D(D),
        .Q(Q)
    );


    // ========================================================
    // CLOCK
    // ========================================================

    initial begin

        clk = 1'b0;

        forever #5 clk = ~clk;

    end


    // ========================================================
    // TEST
    // ========================================================

    initial begin

        $display("");
        $display("================================================");
        $display("              4-BIT REGISTER TEST");
        $display("================================================");

        $display(
            "Time | Reset | Load | D    | Q"
        );

        $display(
            "--------------------------------"
        );


        // ----------------------------------------------------
        // RESET
        // ----------------------------------------------------

        reset = 1;
        load = 0;
        D = 4'b0000;

        #2;

        $display(
            "%4t |   %b   |  %b   | %b | %b",
            $time,
            reset,
            load,
            D,
            Q
        );


        #8;

        reset = 0;


        // ----------------------------------------------------
        // LOAD 1010
        // ----------------------------------------------------

        load = 1;
        D = 4'b1010;

        @(posedge clk);
        #1;

        $display(
            "%4t |   %b   |  %b   | %b | %b",
            $time,
            reset,
            load,
            D,
            Q
        );


        // ----------------------------------------------------
        // LOAD 1100
        // ----------------------------------------------------

        D = 4'b1100;

        @(posedge clk);
        #1;

        $display(
            "%4t |   %b   |  %b   | %b | %b",
            $time,
            reset,
            load,
            D,
            Q
        );


        // ----------------------------------------------------
        // HOLD
        // ----------------------------------------------------

        load = 0;
        D = 4'b0011;

        @(posedge clk);
        #1;

        $display(
            "%4t |   %b   |  %b   | %b | %b",
            $time,
            reset,
            load,
            D,
            Q
        );


        // ----------------------------------------------------
        // LOAD 0101
        // ----------------------------------------------------

        load = 1;
        D = 4'b0101;

        @(posedge clk);
        #1;

        $display(
            "%4t |   %b   |  %b   | %b | %b",
            $time,
            reset,
            load,
            D,
            Q
        );


        // ----------------------------------------------------
        // RESET AGAIN
        // ----------------------------------------------------

        reset = 1;
        load = 0;

        #2;

        $display(
            "%4t |   %b   |  %b   | %b | %b",
            $time,
            reset,
            load,
            D,
            Q
        );


        $display("");
        $display("================================================");
        $display("          REGISTER TEST COMPLETED");
        $display("================================================");

        $finish;

    end

endmodule
