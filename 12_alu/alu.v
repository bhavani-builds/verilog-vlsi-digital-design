// ============================================================
// VERILOG VLSI DIGITAL DESIGN
// STEP 12: 4-BIT ARITHMETIC LOGIC UNIT
// ============================================================

module alu_4bit (
    input  wire [3:0] A,
    input  wire [3:0] B,

    input wire [2:0] OP,

    output reg [3:0] RESULT,
    output reg CARRY,
    output reg ZERO
);

    reg [4:0] TEMP;

    always @(*) begin

        // Default values
        RESULT = 4'b0000;
        CARRY  = 1'b0;
        TEMP   = 5'b00000;

        case (OP)

            // ------------------------------------------------
            // 000 : ADD
            // ------------------------------------------------

            3'b000: begin

                TEMP = A + B;

                RESULT = TEMP[3:0];

                CARRY = TEMP[4];

            end


            // ------------------------------------------------
            // 001 : SUBTRACT
            // ------------------------------------------------

            3'b001: begin

                RESULT = A - B;

                CARRY = 1'b0;

            end


            // ------------------------------------------------
            // 010 : AND
            // ------------------------------------------------

            3'b010: begin

                RESULT = A & B;

            end


            // ------------------------------------------------
            // 011 : OR
            // ------------------------------------------------

            3'b011: begin

                RESULT = A | B;

            end


            // ------------------------------------------------
            // 100 : XOR
            // ------------------------------------------------

            3'b100: begin

                RESULT = A ^ B;

            end


            // ------------------------------------------------
            // 101 : NOT A
            // ------------------------------------------------

            3'b101: begin

                RESULT = ~A;

            end


            // ------------------------------------------------
            // 110 : SHIFT LEFT
            // ------------------------------------------------

            3'b110: begin

                RESULT = A << 1;

            end


            // ------------------------------------------------
            // 111 : SHIFT RIGHT
            // ------------------------------------------------

            3'b111: begin

                RESULT = A >> 1;

            end


            default: begin

                RESULT = 4'b0000;
                CARRY = 1'b0;

            end

        endcase


        // ZERO FLAG
        if (RESULT == 4'b0000)

            ZERO = 1'b1;

        else

            ZERO = 1'b0;

    end

endmodule
