// ============================================================
// TESTBENCH: 4-to-1 MUX AND 1-to-4 DEMUX
// ============================================================

`timescale 1ns/1ps

module tb_mux_demux;

    // ========================================================
    // MUX SIGNALS
    // ========================================================

    reg [3:0] I;
    reg [1:0] S;

    wire MUX_Y;


    // ========================================================
    // DEMUX SIGNALS
    // ========================================================

    reg D;

    wire [3:0] DEMUX_Y;


    // ========================================================
    // MUX DUT
    // ========================================================

    mux_4to1 MUX_DUT (
        .I(I),
        .S(S),
        .Y(MUX_Y)
    );


    // ========================================================
    // DEMUX DUT
    // ========================================================

    demux_1to4 DEMUX_DUT (
        .D(D),
        .S(S),
        .Y(DEMUX_Y)
    );


    // ========================================================
    // TEST
    // ========================================================

    initial begin

        // ----------------------------------------------------
        // MUX TEST
        // ----------------------------------------------------

        $display("");
        $display("================================================");
        $display("             4-to-1 MUX TEST");
        $display("================================================");

        I = 4'b1010;

        $display(
            "Inputs = %b",
            I
        );

        $display("");
        $display(
            "S1 S0 | Selected Output"
        );

        $display(
            "------------------------"
        );


        S = 2'b00;
        #10;

        $display(
            " %b  %b  |       %b",
            S[1],
            S[0],
            MUX_Y
        );


        S = 2'b01;
        #10;

        $display(
            " %b  %b  |       %b",
            S[1],
            S[0],
            MUX_Y
        );


        S = 2'b10;
        #10;

        $display(
            " %b  %b  |       %b",
            S[1],
            S[0],
            MUX_Y
        );


        S = 2'b11;
        #10;

        $display(
            " %b  %b  |       %b",
            S[1],
            S[0],
            MUX_Y
        );


        // ----------------------------------------------------
        // DEMUX TEST
        // ----------------------------------------------------

        $display("");
        $display("================================================");
        $display("             1-to-4 DEMUX TEST");
        $display("================================================");

        D = 1'b1;

        $display(
            "Data = %b",
            D
        );

        $display("");
        $display(
            "S1 S0 | Y3 Y2 Y1 Y0"
        );

        $display(
            "--------------------"
        );


        S = 2'b00;
        #10;

        $display(
            " %b  %b  |  %b  %b  %b  %b",
            S[1],
            S[0],
            DEMUX_Y[3],
            DEMUX_Y[2],
            DEMUX_Y[1],
            DEMUX_Y[0]
        );


        S = 2'b01;
        #10;

        $display(
            " %b  %b  |  %b  %b  %b  %b",
            S[1],
            S[0],
            DEMUX_Y[3],
            DEMUX_Y[2],
            DEMUX_Y[1],
            DEMUX_Y[0]
        );


        S = 2'b10;
        #10;

        $display(
            " %b  %b  |  %b  %b  %b  %b",
            S[1],
            S[0],
            DEMUX_Y[3],
            DEMUX_Y[2],
            DEMUX_Y[1],
            DEMUX_Y[0]
        );


        S = 2'b11;
        #10;

        $display(
            " %b  %b  |  %b  %b  %b  %b",
            S[1],
            S[0],
            DEMUX_Y[3],
            DEMUX_Y[2],
            DEMUX_Y[1],
            DEMUX_Y[0]
        );


        $display("");
        $display("================================================");
        $display("        MUX / DEMUX TEST COMPLETED");
        $display("================================================");

        $finish;

    end

endmodule
